/** タイルに載せる短い名前（2〜4文字）。「温泉郷」「温泉」と（）の補足を落とし、4文字を超えたら4文字で切る */
export function shortAreaName(name: string): string {
  const s = name.replace(/[（(].*?[）)]/g, "").replace(/温泉郷$|温泉$/, "").trim();
  return Array.from(s).slice(0, 4).join("");
}
